/** Dynamic question ids name real quiz/survey controls; never expose those ids as the learner's explanation. */
export function describeError(code: string): string {
  if (Object.hasOwn(ERRORS, code)) return ERRORS[code]
  const answer = /^(missing|invalid|too_long)_(q|s)_[A-Za-z0-9-]+(?:_\d+)?$/.exec(code)
  if (answer) {
    if (answer[2] === 's') return answer[1] === 'too_long' ? 'your survey answer is too long. Shorten it before sending the survey.' : 'choose a rating from the survey’s options.'
    return answer[1] === 'too_long' ? 'your quiz answer is too long. Shorten it before submitting.' : 'check your quiz answer and use one of the options shown.'
  }
  return code.replace(/_/g, ' ') + '.'
}
