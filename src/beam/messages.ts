export const MESSAGE_CATALOG: Record<Language, Record<string, string>> = { 'en-US': {}, 'es-US': spanish }
export function message(language: Language | undefined, key: string, values: Record<string, string | number> = {}) {
  const catalog = MESSAGE_CATALOG[language ?? 'en-US'], text = catalog[key] ?? key
  return text.replace(/\{(\w+)\}/g, (placeholder, name) => typeof values[name] === 'number' ? new Intl.NumberFormat(language ?? 'en-US').format(values[name] as number) : String(values[name] ?? placeholder))
}
export const t = (actor: Pick<Actor, 'locale'> | null, key: string, values: Record<string, string | number> = {}) => message(actor?.locale, key, values)
export const localeNumber = (actor: Pick<Actor, 'locale'>, value: number) => new Intl.NumberFormat(actor.locale ?? 'en-US').format(value)

export function counted(actor: Pick<Actor, 'locale'>, singular: string, plural: string, value: number) {
 return `${localeNumber(actor, value)} ${t(actor, new Intl.PluralRules(actor.locale ?? 'en-US').select(value) === 'one' ? singular : plural)}`
}

/** Stored quiz decisions retain their original audit wording; localize their learner presentation. */
export function quizDecision(actor: Pick<Actor, 'locale'>, decision: string) {
 const retry = /^retry allowed: (\d+) attempts? remaining$/.exec(decision)
 return retry ? t(actor, 'retry allowed: {n} attempts remaining', { n: localeNumber(actor, Number(retry[1])) }) : t(actor, decision)
}

/** Translate generated scoring clauses for display; the recorded rule itself remains immutable. */
export function quizScoringRule(actor: Pick<Actor, 'locale'>, rule: string) {
 return rule.split('; ').map(clause => {
  const pass = /^pass at (\d+)%$/.exec(clause)
  if (pass) return t(actor, 'pass at {percent}%', { percent: Number(pass[1]) })
  const timed = /^time limit (\d+) minutes(?: plus (\d+) minutes extra time)?$/.exec(clause)
  if (timed) return t(actor, timed[2] ? 'time limit {minutes} minutes plus {extra} minutes extra time' : 'time limit {minutes} minutes', { minutes: Number(timed[1]), extra: Number(timed[2] ?? 0) })
  return t(actor, clause)
 }).join('; ')
}
