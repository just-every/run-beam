  const externalCookie = await h.signIn('synthetic-beam-1@example.test', { requested: true })
  const other = await invite(partner, 'synthetic-beam-2@example.test', 'Partner learner')
  const partnerCookie = await h.signIn('synthetic-beam-2@example.test', { requested: true })
  const separate = await invite(partner, 'synthetic-beam-1@example.test', 'Partner identity')
  assert.notEqual(external.id, separate.id)
  const call = async (p, door, cookie, body, status = 200) => {
    const response = await h.raw(`/api/beam/portal/${p.id}/${door}`, { cookie, body })
    const text = await response.text()
    assert.equal(response.status, status, `${door}: ${response.status} ${text.slice(0, 180)}`)
    assert.equal(response.headers.get('cache-control'), 'no-store')
    return JSON.parse(text)
  }
  assert.equal(external.state, 'claim_required')
  await call(customer, 'consent', externalCookie, undefined, 404)
