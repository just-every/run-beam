  const freshEnrollment = await call(customer, 'enroll', cookies.owner, { identity: external.id, revision: freshRevision })
  const freshStudy = await study(externalCookie, undefined, 200, customer, freshEnrollment.id)
  assert.equal(freshStudy.revision.id, freshRevision)
  assert.equal(freshStudy.lessonsRead, 0)
  assert.equal(freshStudy.lessons.length, 2)
  assert.ok(freshStudy.lessons.every(row => row.completedAt === null))
  const unavailable = freshStudy.lessons.find(row => row.title === 'Additional material')
  assert.deepEqual([unavailable.body, unavailable.available], [null, false])
  await study(externalCookie, { enrollment: freshEnrollment.id, lesson: unavailable.id }, 409, customer, freshEnrollment.id)
  await study(externalCookie, { enrollment: enrolled.id, lesson: freshStudy.lessons[0].id }, 404)
  assert.equal((await study(externalCookie)).lessonsRead, 1)
