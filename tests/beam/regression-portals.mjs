  assert.deepEqual(catalog.courses.map(row => row.revision), [c.revision])
  assert.equal(catalog.state, 'preparation')
  assert.equal(catalog.theme.primary, theme.primary)
  assert.ok(!JSON.stringify(catalog).includes('source_version_ids'))
  await api('owner', 'theme.save', { ...theme, primary: '#442233' })
  assert.equal((await call(customer, 'catalog', externalCookie)).theme.primary, theme.primary)
  await api('manager', 'portal.theme', { portal: customer.id, ...theme }, 403)
  await api('owner', 'portal.theme', { portal: customer.id, ...theme, primary: '#eeeeee' }, 400)
  await api('owner', 'portal.theme', { portal: customer.id, ...theme, primary: '#442233' })
  assert.equal((await call(customer, 'catalog', externalCookie)).theme.primary, '#442233')
  assert.equal((await call(partner, 'catalog', partnerCookie)).theme.primary, theme.primary)
  for (const door of ['roster', 'report']) await call(customer, door, externalCookie, undefined, 403)
  await call(customer, 'enroll', externalCookie, { identity: external.id, revision: c.revision }, 403)
  await api('owner', 'portal.admin', { portal: customer.id, identity: other.id }, 404)
  await api('owner', 'portal.admin', { portal: partner.id, identity: separate.id }, 404)
  await api('owner', 'portal.admin', { portal: customer.id, identity: external.id })
  const roster = await call(customer, 'roster', externalCookie)
  assert.deepEqual(roster.identities.map(row => row.id), [external.id])
  assert.ok(!JSON.stringify(roster).includes('operator_id'))
  const enrolled = await call(customer, 'enroll', externalCookie, { identity: external.id, revision: c.revision })
  assert.deepEqual(await call(customer, 'enroll', externalCookie, { identity: external.id, revision: c.revision }), enrolled)
  assert.deepEqual(await call(customer, 'enroll', cookies.owner, { identity: external.id, revision: c.revision }), enrolled)
  await call(customer, 'enroll', externalCookie, { identity: other.id, revision: c.revision }, 404)
  // A shared catalog does not confer access to somebody else's enrollment or source files.
  const study = (cookie, body, status = 200, p = customer, enrollment = enrolled.id, door = 'learning') =>
    call(p, `${door}?enrollment=${enrollment}`, cookie, body, status)
  assert.deepEqual((await call(customer, 'catalog', externalCookie)).enrollments, [{ id: enrolled.id, revision: c.revision }])
  const unread = await study(externalCookie)
  assert.equal(unread.revision.id, c.revision)
  assert.deepEqual(unread.lessons.map(row => [row.title, row.body, row.available, row.completedAt]), [['Procedure', 'Perform the owned procedure.', true, null]])
  assert.equal(unread.resumeLesson, unread.lessons[0].id)
  assert.equal(unread.lessonsRead, 0)
  assert.equal(unread.completion, null)
  await study(partnerCookie, undefined, 404)
  await study(partnerCookie, undefined, 404, partner)
  await study(cookies.owner, { enrollment: enrolled.id, lesson: unread.lessons[0].id }, 404)
  await call(customer, 'learning', externalCookie, undefined, 400)
  await call(customer, 'claim', reusedCookie, { identity: reused.id })
  await call(customer, 'consent', reusedCookie, { accept: true, noticeVersion: 1 })
  await study(reusedCookie, undefined, 404)
  await study(reusedCookie, { enrollment: enrolled.id, lesson: unread.lessons[0].id }, 404)
  await study(reusedCookie, undefined, 404, customer, enrolled.id, 'progress.json')
  await api('owner', 'portal.revoke', { portal: customer.id, identity: reused.id })
  // A learner needs no administrator grant to record their own progress.
  await api('owner', 'portal.admin', { portal: customer.id, identity: external.id, revoke: true })
  const read = await study(externalCookie, { enrollment: enrolled.id, lesson: unread.lessons[0].id })
  assert.equal(read.lessonsRead, 1)
  assert.equal(read.resumeLesson, null)
  assert.equal(typeof read.lessons[0].completedAt, 'number')
  assert.equal(read.completion, null)
  assert.deepEqual(await study(externalCookie, { enrollment: enrolled.id, lesson: unread.lessons[0].id }), read, 'repeat reads preserve the original evidence time')
  const download = await h.raw(`/api/beam/portal/${customer.id}/progress.json?enrollment=${enrolled.id}`, { cookie: externalCookie })
  assert.equal(download.status, 200)
  assert.match(download.headers.get('content-disposition'), /^attachment;/)
  const receipt = await download.json()
  assert.deepEqual(receipt.lessons, [{ id: unread.lessons[0].id, title: 'Procedure', completedAt: read.lessons[0].completedAt }])
  assert.equal(receipt.revision.id, c.revision)
  assert.equal(receipt.completion, null)
  await study(externalCookie, { enrollment: enrolled.id, lesson: unread.lessons[0].id }, 405, customer, enrolled.id, 'progress.json')
  const head = await h.raw(`/api/beam/portal/${customer.id}/learning?enrollment=${enrolled.id}`, { cookie: externalCookie, method: 'HEAD' })
  assert.equal(head.status, 200)
  assert.equal(await head.text(), '')
  for (const door of ['learning', 'progress.json']) {
    const path = `/api/beam/portal/${customer.id}/${door}?enrollment=${enrolled.id}`
    assert.equal((await h.raw(path)).status, 401)
    assert.equal((await h.fetch(path, { headers: { cookie: externalCookie, authorization: 'Bearer synthetic-beam-7' } })).status, 403)
  }
  await api('owner', 'course.retire', { course: c.id, reason: 'Pause external delivery for review.' })
  await study(externalCookie, undefined, 404)
  await study(externalCookie, { enrollment: enrolled.id, lesson: unread.lessons[0].id }, 404)
  await study(externalCookie, undefined, 404, customer, enrolled.id, 'progress.json')
  await api('owner', 'course.reinstate', { course: c.id })
  assert.deepEqual(await study(externalCookie), read)

  const privateCourse = await course('Private employee course')
  const privateLesson = (await api('reviewer', `revisions/${privateCourse.revision}`)).lessons[0].id
  await study(externalCookie, { enrollment: enrolled.id, lesson: privateLesson }, 404)
  // Publishing and sharing a later revision never replaces the old enrollment or its progress.
  const draft = await api('author', `courses/${c.id}`)
  let edited = await api('author', 'course.lesson', { course: c.id, draftVersion: draft.draftVersion, title: 'Additional material', body: 'New revision text.', sources: [] })
  edited = await api('author', 'course.block', { course: c.id, draftVersion: edited.draftVersion, lesson: edited.draft.lessons[1].id, content: { kind: 'link', text: 'External resource', url: 'https://example.test/material' } })
