import assert from 'node:assert/strict'
import { file } from './harness.mjs'

// Public HTTP proof of preparation boundaries; no simulated external learning.
export async function enterprisePortalsCheck(f) {
  const { api, h, cookies, ids, course } = f
  const theme = { primary: '#19334d', accent: '#235238', signinHeading: 'Training', signinText: 'Welcome', senderName: 'Training' }
  await api('owner', 'theme.save', theme)
  const create = (kind, status = 200) => api('owner', 'portal.create', { kind, name: `${kind} training`, consentText: `Explicit ${kind} training consent`, confirm: true }, status)
  await api('manager', 'portal.create', { kind: 'customer', name: 'Forbidden', consentText: 'No', confirm: true }, 403)
  await api('owner', 'portal.create', { kind: 'customer', name: 'Unconfirmed', consentText: 'No' }, 400)
  const employee = await create('employee'), customer = await create('customer'), partner = await create('partner')
  assert.equal((await api('owner', 'portals')).portals.length, 3)
  await api('manager', 'portals', undefined, 403)
  await create('employee', 409)
  const c = await course('Explicitly shared induction')
  for (const p of [employee, customer, partner]) await api('owner', 'portal.share', { portal: p.id, revision: c.revision, confirm: true })
  const unpublished = await api('author', 'course.create', { title: 'Private draft', reviewer: ids.reviewer })
  await api('owner', 'portal.share', { portal: customer.id, revision: unpublished.id, confirm: true }, 409)
  await api('owner', 'portal.share', { portal: customer.id, revision: c.revision }, 400)
  const invite = (p, email, name) => api('owner', 'portal.invite', { portal: p.id, email, name, sendInvitation: true })
  const imported = await api('owner', 'people.import', { file: file('portal-roster.csv', 'Employee ID,Name,Email\r\nsynthetic-beam-4,Unlinked employee,synthetic-beam-4@example.test\r\n', 'text/csv') })
  assert.equal(imported.created.length, 1)
  const sent = h.mails.length
  const refused = await api('owner', 'portal.invite', { portal: customer.id, email: 'synthetic-beam-4@example.test', name: 'Unlinked employee', sendInvitation: true }, 409)
  assert.equal(refused.error, 'employee_identity_link_required')
  assert.equal(h.mails.length, sent)
  const external = await invite(customer, 'synthetic-beam-1@example.test', 'Customer learner')
  const externalCookie = await h.signIn('synthetic-beam-1@example.test', { requested: true })
  const other = await invite(partner, 'synthetic-beam-2@example.test', 'Partner learner')
  const partnerCookie = await h.signIn('synthetic-beam-2@example.test', { requested: true })
  const separate = await invite(partner, 'synthetic-beam-1@example.test', 'Partner identity')
  assert.notEqual(external.id, separate.id)
  const call = async (p, door, cookie, body, status = 200) => {
    const response = await h.raw(`/api/beam/portal/${p.id}/${door}`, { cookie, body })
    const text = await response.text()
    assert.equal(response.status, status, `${door}: ${response.status} ${text.slice(0, 180)}`)
    assert.equal(response.headers.get('cache-control'), 'no-store')
    return JSON.parse(text)
  }
  await call(customer, 'catalog', externalCookie, undefined, 403)
  const consent = await call(customer, 'consent', externalCookie)
  assert.equal(consent.accepted, false)
  assert.equal(consent.consentText, 'Explicit customer training consent')
  await call(customer, 'consent', externalCookie, { accept: false }, 400)
  await call(customer, 'consent', externalCookie, { accept: true })
  await call(partner, 'catalog', externalCookie, undefined, 403)
  await call(partner, 'consent', partnerCookie, { accept: true })
  await call(customer, 'catalog', partnerCookie, undefined, 404)
  const catalog = await call(customer, 'catalog', externalCookie)
  assert.deepEqual(catalog.courses.map(row => row.revision), [c.revision])
  assert.equal(catalog.state, 'preparation')
  assert.equal(catalog.theme.primary, theme.primary)
  assert.ok(!JSON.stringify(catalog).includes('source_version_ids'))
  await api('owner', 'theme.save', { ...theme, primary: '#442233' })
  assert.equal((await call(customer, 'catalog', externalCookie)).theme.primary, theme.primary)
  await api('manager', 'portal.theme', { portal: customer.id, ...theme }, 403)
  await api('owner', 'portal.theme', { portal: customer.id, ...theme, primary: '#eeeeee' }, 400)
  await api('owner', 'portal.theme', { portal: customer.id, ...theme, primary: '#442233' })
  assert.equal((await call(customer, 'catalog', externalCookie)).theme.primary, '#442233')
  assert.equal((await call(partner, 'catalog', partnerCookie)).theme.primary, theme.primary)
  for (const door of ['roster', 'report']) await call(customer, door, externalCookie, undefined, 403)
  await call(customer, 'enroll', externalCookie, { identity: external.id, revision: c.revision }, 403)
  await api('owner', 'portal.admin', { portal: customer.id, identity: other.id }, 404)
  await api('owner', 'portal.admin', { portal: partner.id, identity: separate.id }, 404)
  await api('owner', 'portal.admin', { portal: customer.id, identity: external.id })
  const roster = await call(customer, 'roster', externalCookie)
  assert.deepEqual(roster.identities.map(row => row.id), [external.id])
  assert.ok(!JSON.stringify(roster).includes('operator_id'))
  const enrolled = await call(customer, 'enroll', externalCookie, { identity: external.id, revision: c.revision })
  assert.deepEqual(await call(customer, 'enroll', externalCookie, { identity: external.id, revision: c.revision }), enrolled)
  assert.deepEqual(await call(customer, 'enroll', cookies.owner, { identity: external.id, revision: c.revision }), enrolled)
  await call(customer, 'enroll', externalCookie, { identity: other.id, revision: c.revision }, 404)
  assert.deepEqual((await call(customer, 'report', externalCookie)).enrollments.map(row => row.identity), [external.id])
  await call(partner, 'roster', externalCookie, undefined, 403)
  // An external account gains no employee member or authority, even after a portal grant.
  for (const path of ['/app', '/app/people', '/app/learning', '/app/reports.csv', '/app/reports.xlsx', '/app/audit.csv', `/app/certificates/${enrolled.id}.pdf`, `/app/files/source/${c.revision}`,
    '/api/beam/me', '/api/beam/people', '/api/beam/directory', '/api/beam/report', '/api/beam/sources', '/api/beam/courses', `/api/beam/revisions/${c.revision}`, `/api/beam/assignments/${enrolled.id}`, '/api/beam/records/me', '/api/beam/units', '/api/beam/roles', '/api/beam/audit', '/api/beam/data-export']) {
    const response = await h.raw(path, { cookie: externalCookie })
    assert.ok([403, 404].includes(response.status), `${path}: ${response.status}`)
    assert.ok(!(await response.text()).includes('Perform the owned procedure.'))
  }
  await h.api('portal.admin', externalCookie, { portal: partner.id, identity: other.id }, 403)
  for (const door of [`catalog/${c.revision}`, 'report.csv', 'download', 'admin']) {
    const response = await h.raw(`/api/beam/portal/${customer.id}/${door}`, { cookie: externalCookie })
    assert.equal(response.status, 404)
  }
  assert.equal((await h.fetch(`/api/beam/portal/${customer.id}/enroll`, { method: 'POST', headers: { cookie: externalCookie, 'content-type': 'application/json' }, body: '{}' })).status, 403)
  assert.equal((await h.fetch(`/api/beam/portal/${customer.id}/catalog`, { headers: { authorization: 'Bearer synthetic-beam-3' } })).status, 403)
  assert.equal((await h.raw(`/api/beam/portal/${customer.id}/catalog`)).status, 401)
  const viewed = await h.raw('/api/beam/view.start', { cookie: cookies.owner, body: { learner: ids.learner } })
  assert.equal(viewed.status, 200)
  const viewingCookie = `${cookies.owner}; beam_view=${(await viewed.json()).id}`
  await call(customer, 'catalog', viewingCookie, undefined, 403)
  await call(customer, 'enroll', viewingCookie, { identity: external.id, revision: c.revision }, 403)
  const exported = await (await h.raw('/app/data-export.json', { cookie: cookies.owner })).json()
  assert.ok(exported.records.beam_portal_enrollments.rows.some(row => row.id === enrolled.id))
  assert.ok(exported.records.beam_portal_identities.rows.every(row => !('operator_id' in row)))
  assert.equal(exported.records.beam_portal_administrators, undefined)
  await call(customer, 'consent', externalCookie, { withdraw: true })
  await call(customer, 'catalog', externalCookie, undefined, 403)
  assert.deepEqual((await call(customer, 'roster', cookies.owner)).identities, [])
  assert.deepEqual((await call(customer, 'report', cookies.owner)).enrollments, [])
  await call(customer, 'consent', externalCookie, { accept: true })
  await call(customer, 'roster', externalCookie, undefined, 403)
  await api('owner', 'portal.admin', { portal: customer.id, identity: external.id })
  await api('owner', 'portal.admin', { portal: customer.id, identity: external.id, revoke: true })
  await call(customer, 'roster', externalCookie, undefined, 403)
  await api('owner', 'portal.share', { portal: customer.id, revision: c.revision, confirm: true, revoke: true })
  assert.deepEqual((await call(customer, 'catalog', externalCookie)).courses, [])
  await call(customer, 'enroll', cookies.owner, { identity: external.id, revision: c.revision }, 404)
  assert.deepEqual((await call(customer, 'report', cookies.owner)).enrollments, [])
  await api('owner', 'portal.revoke', { portal: customer.id, identity: external.id })
  await call(customer, 'catalog', externalCookie, undefined, 404)
  await call(customer, 'consent', externalCookie, { accept: true }, 404)
  assert.equal((await api('learner', 'me')).id, ids.learner)
  assert.ok(!(await api('owner', 'people')).members.some(row => row.name === 'Customer learner'))
}
