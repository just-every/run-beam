  await api('owner', 'portal.share', { portal: customer.id, revision: unpublished.id, confirm: true }, 409)
  await api('owner', 'portal.share', { portal: customer.id, revision: c.revision }, 400)
  const invite = (p, email, name) => api('owner', 'portal.invite', { portal: p.id, email, name, sendInvitation: true })
  const imported = await api('owner', 'people.import', { file: file('portal-roster.csv', 'Employee ID,Name,Email\r\nsynthetic-beam-4,Unlinked employee,synthetic-beam-4@example.test\r\n', 'text/csv') })
